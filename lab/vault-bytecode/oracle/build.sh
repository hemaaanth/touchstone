#!/usr/bin/env bash
# Rebuild the bytecode-only lab from oracle/HiddenVault.sol.
# Writes src/BytecodeVault.runtime.hex (what Mythril and Heimdall read) and
# src/BytecodeVault.sol (a stub that installs that exact runtime code, so the
# Foundry harm gate can see a CREATE from scope code). Offline: it needs the
# foundry image and the warmed foundry-svm volume (see spike/lib/sandbox.mjs).
set -euo pipefail
LAB="$(cd "$(dirname "$0")/.." && pwd)"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
mkdir -p "$TMP/src"
cp "$LAB/oracle/HiddenVault.sol" "$TMP/src/"
# No CBOR metadata: the runtime code carries no source hash, and rebuilds are stable.
printf '[profile.default]\nsrc = "src"\nout = "out"\nbytecode_hash = "none"\ncbor_metadata = false\n' > "$TMP/foundry.toml"
docker run --rm --pull=never --network none -v foundry-svm:/home/foundry/.svm \
  -v "$TMP":/work -w /work ghcr.io/foundry-rs/foundry:latest "forge build --offline --use 0.8.38 --skip test" >/dev/null
HEX="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["deployedBytecode"]["object"][2:])' "$TMP/out/HiddenVault.sol/HiddenVault.json")"
printf '%s\n' "$HEX" > "$LAB/src/BytecodeVault.runtime.hex"
cat > "$LAB/src/BytecodeVault.sol" <<SOL
// SPDX-License-Identifier: MIT
pragma solidity ^0.8.20;

/// @title BytecodeVault
/// @notice A deployed-bytecode-only target. Its Solidity source is not given.
///         An ETH vault was compiled and only its runtime bytecode is shipped,
///         in BytecodeVault.runtime.hex next to this file. Deploying this stub
///         installs that exact runtime bytecode at the new address.
/// @dev Generated by lab/vault-bytecode/oracle/build.sh. Do not edit by hand.
///      The constructor also stores the deployer in slot 0, as the original
///      constructor did. Use \`new BytecodeVault()\` in a test to deploy it.
contract BytecodeVault {
    constructor() payable {
        bytes memory code = hex"$HEX";
        assembly {
            sstore(0, caller())
            return(add(code, 0x20), mload(code))
        }
    }
}
SOL
echo "wrote $LAB/src/BytecodeVault.runtime.hex ($(( ${#HEX} / 2 )) bytes) and BytecodeVault.sol"
